const quizState = {
  currentQuizKey: null,
  questions: [],
  score: 0,
  index: 0,
  timer: 15,
  timerId: null,
  answered: false,
  finished: false
};

const modalRefs = {
  login: document.getElementById("loginModal"),
  signup: document.getElementById("signupModal"),
  quiz: document.getElementById("quizModal")
};

const quizElements = {
  category: document.getElementById("quizCategory"),
  title: document.getElementById("quizTitle"),
  question: document.getElementById("quizQuestion"),
  options: document.getElementById("answerOptions"),
  explanation: document.getElementById("explanationBox"),
  counter: document.getElementById("questionCounter"),
  score: document.getElementById("scoreDisplay"),
  timer: document.getElementById("timerValue"),
  progress: document.getElementById("progressFill"),
  nextButton: document.getElementById("nextQuestionBtn")
};

function openModal(id) {
  const modal = document.getElementById(id);
  if (!modal) return;
  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");
}

function closeModal(id) {
  const modal = document.getElementById(id);
  if (!modal) return;
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
}

function closeAllModals() {
  Object.values(modalRefs).forEach((modal) => {
    if (modal) {
      modal.classList.remove("open");
      modal.setAttribute("aria-hidden", "true");
    }
  });
}

function setupModalTriggers() {
  document.querySelectorAll("[data-open-modal]").forEach((button) => {
    button.addEventListener("click", (event) => {
      event.preventDefault();
      const targetId = button.getAttribute("data-open-modal");
      closeAllModals();
      openModal(targetId);
    });
  });

  document.querySelectorAll(".close-modal").forEach((button) => {
    button.addEventListener("click", () => {
      const currentModal = button.closest(".modal");
      if (currentModal) {
        currentModal.classList.remove("open");
        currentModal.setAttribute("aria-hidden", "true");
      }
      if (currentModal && currentModal.id === "quizModal") {
        clearInterval(quizState.timerId);
        quizState.timerId = null;
        quizState.finished = false;
      }
    });
  });

  document.querySelectorAll(".modal").forEach((modal) => {
    modal.addEventListener("click", (event) => {
      if (event.target === modal) {
        modal.classList.remove("open");
        modal.setAttribute("aria-hidden", "true");
        if (modal.id === "quizModal") {
          clearInterval(quizState.timerId);
          quizState.timerId = null;
          quizState.finished = false;
        }
      }
    });
  });
}

function setupAuthForms() {
  const loginForm = document.getElementById("loginForm");
  const signupForm = document.getElementById("signupForm");
  const contactForm = document.getElementById("contactForm");

  if (loginForm) {
    loginForm.addEventListener("submit", (event) => {
      event.preventDefault();
      alert("Login successful! Welcome back to IslamicQuiz.");
      loginForm.reset();
      closeModal("loginModal");
    });
  }

  if (signupForm) {
    signupForm.addEventListener("submit", (event) => {
      event.preventDefault();
      const formData = new FormData(signupForm);
      const password = formData.get("password");
      const confirmPassword = formData.get("confirmPassword");

      if (password !== confirmPassword) {
        alert("Passwords do not match. Please try again.");
        return;
      }

      alert("Account created successfully! You can now begin learning.");
      signupForm.reset();
      closeModal("signupModal");
    });
  }

  if (contactForm) {
    contactForm.addEventListener("submit", (event) => {
      event.preventDefault();
      alert("Your message has been sent. We will get back to you soon.");
      contactForm.reset();
    });
  }
}

function setupFilters() {
  const filterButtons = document.querySelectorAll(".filter-chip");
  const quizCards = document.querySelectorAll(".quiz-card");

  filterButtons.forEach((button) => {
    button.addEventListener("click", () => {
      const filterValue = button.getAttribute("data-filter");

      filterButtons.forEach((chip) => chip.classList.toggle("active", chip === button));

      quizCards.forEach((card) => {
        const matches = filterValue === "all" || card.dataset.category === filterValue;
        card.classList.toggle("hidden", !matches);
      });
    });
  });
}

function startTimer() {
  clearInterval(quizState.timerId);
  quizState.timer = 15;
  quizState.timerId = setInterval(() => {
    quizState.timer -= 1;
    quizElements.timer.textContent = String(quizState.timer);

    if (quizState.timer <= 0) {
      clearInterval(quizState.timerId);
      quizState.timerId = null;
      if (!quizState.answered) {
        handleAnswer(null);
      }
    }
  }, 1000);
}

function updateProgress() {
  const current = quizState.index + 1;
  const total = quizState.questions.length;
  const percent = (current / total) * 100;
  quizElements.progress.style.width = `${Math.min(percent, 100)}%`;
  quizElements.counter.textContent = `${Math.min(current, total)} / ${total}`;
}

function renderQuestion() {
  const currentQuestion = quizState.questions[quizState.index];
  if (!currentQuestion) return;

  quizState.answered = false;
  quizState.finished = false;

  quizElements.question.textContent = currentQuestion.question;
  quizElements.explanation.textContent = "";
  quizElements.explanation.classList.add("hidden");
  quizElements.score.textContent = `Score: ${quizState.score}`;
  quizElements.nextButton.textContent = quizState.index === quizState.questions.length - 1 ? "Finish" : "Next";

  quizElements.options.innerHTML = currentQuestion.options
    .map(
      (option, index) => `
        <button type="button" class="answer-option" data-index="${index}">${option}</button>
      `
    )
    .join("");

  quizElements.options.querySelectorAll(".answer-option").forEach((button) => {
    button.addEventListener("click", () => handleAnswer(Number(button.dataset.index)));
  });

  updateProgress();
  quizElements.timer.textContent = String(quizState.timer);
  startTimer();
}

function showResultScreen() {
  clearInterval(quizState.timerId);
  quizState.timerId = null;
  quizState.finished = true;

  const total = quizState.questions.length;
  const percent = Math.round((quizState.score / total) * 100);

  quizElements.category.textContent = "Assessment complete";
  quizElements.title.textContent = "Quiz Result";
  quizElements.question.textContent = `You scored ${quizState.score} out of ${total} (${percent}%)`;
  quizElements.score.textContent = `Final Score: ${quizState.score}`;
  quizElements.options.innerHTML = `
    <div class="result-summary">
      <p>${percent >= 80 ? "Excellent work!" : percent >= 60 ? "Great effort!" : "Keep learning — you’re improving."}</p>
      <p>Review the explanations and try another quiz to strengthen your understanding.</p>
    </div>
  `;

  const feedback = percent >= 80
    ? "Outstanding! Your understanding of Islamic knowledge is strong. Keep building on this momentum."
    : percent >= 60
      ? "Well done! You have a solid foundation. A little more review will take you even further."
      : "You are on the right path. Keep revising and retaking quizzes to grow in confidence and knowledge.";

  quizElements.explanation.innerHTML = `<strong>Feedback:</strong> ${feedback}`;
  quizElements.explanation.classList.remove("hidden");
  quizElements.progress.style.width = "100%";
  quizElements.counter.textContent = `${total} / ${total}`;
  quizElements.nextButton.textContent = "Close";
}

function handleAnswer(selectedIndex) {
  if (quizState.answered) return;

  clearInterval(quizState.timerId);
  quizState.timerId = null;
  quizState.answered = true;

  const currentQuestion = quizState.questions[quizState.index];
  const buttons = quizElements.options.querySelectorAll(".answer-option");

  buttons.forEach((button) => {
    const optionIndex = Number(button.dataset.index);
    button.disabled = true;

    if (optionIndex === currentQuestion.answer) {
      button.classList.add("correct");
    }

    if (optionIndex === selectedIndex && selectedIndex !== currentQuestion.answer) {
      button.classList.add("wrong");
    }
  });

  if (selectedIndex === currentQuestion.answer) {
    quizState.score += 1;
  }

  quizElements.score.textContent = `Score: ${quizState.score}`;
  quizElements.explanation.innerHTML = `<strong>Explanation:</strong> ${currentQuestion.explanation}`;
  quizElements.explanation.classList.remove("hidden");
}

function advanceQuiz() {
  if (quizState.finished) {
    closeModal("quizModal");
    return;
  }

  if (!quizState.answered) {
    handleAnswer(null);
  }

  if (quizState.index < quizState.questions.length - 1) {
    quizState.index += 1;
    renderQuestion();
    return;
  }

  showResultScreen();
}

function beginQuiz(quizKey) {
  const selectedQuiz = quizBank[quizKey];
  if (!selectedQuiz) return;

  const labelMap = {
    "quran-basics": "Qur'an",
    "hadith-authentic": "Hadith",
    "seerah-life": "Seerah",
    "fiqh-principles": "Fiqh",
    "aqidah-core": "Aqidah",
    "adab-etiquette": "Adab"
  };

  quizState.currentQuizKey = quizKey;
  quizState.questions = [...selectedQuiz];
  quizState.score = 0;
  quizState.index = 0;
  quizState.timer = 15;
  quizState.answered = false;
  quizState.finished = false;

  const titleMap = {
    "quran-basics": "Qur’an Basics",
    "hadith-authentic": "Authentic Hadith",
    "seerah-life": "Life of the Prophet",
    "fiqh-principles": "Islamic Jurisprudence",
    "aqidah-core": "Core Beliefs",
    "adab-etiquette": "Islamic Etiquette"
  };

  quizElements.category.textContent = labelMap[quizKey] || "Quiz";
  quizElements.title.textContent = titleMap[quizKey] || "Quiz";
  quizElements.nextButton.textContent = "Next";
  quizElements.progress.style.width = "0%";
  renderQuestion();
  openModal("quizModal");
}

function setupQuizButtons() {
  document.querySelectorAll("[data-start-quiz]").forEach((button) => {
    button.addEventListener("click", () => {
      const quizKey = button.getAttribute("data-start-quiz");
      beginQuiz(quizKey);
    });
  });

  quizElements.nextButton.addEventListener("click", () => {
    advanceQuiz();
  });
}

function initializeApp() {
  setupModalTriggers();
  setupAuthForms();
  setupFilters();
  setupQuizButtons();

  const navToggle = document.querySelector(".nav-toggle");
  const navPanel = document.querySelector(".nav-panel");

  if (navToggle && navPanel) {
    navToggle.addEventListener("click", () => {
      navPanel.classList.toggle("mobile-open");
      navToggle.classList.toggle("open");
    });
  }
}

initializeApp();
